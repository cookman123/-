def all_keywords() -> set:
    return {w for ws in THEMES.values() for w in ws}


def summary() -> str:
    lines = [f"主題 {len(THEMES)} 個、關鍵詞 {len(all_keywords())} 個、"
             f"預先指定的主題-產業配對 "
             f"{sum(len(v) for v in THEME_SECTOR.values())} 組"]
    for t, ws in THEMES.items():
        pairs = THEME_SECTOR.get(t, [])
        lines.append(f"\n【{t}】{len(ws)} 詞")
        lines.append("  詞：" + "、".join(ws))
        if pairs:
            lines.append("  預期：" + "；".join(
                f"{s}{'↑' if d > 0 else '↓'}（{why}）" for s, d, why in pairs))
    return "\n".join(lines)


